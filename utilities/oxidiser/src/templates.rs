  pub fn boot_main(cfg: &OsConfig) -> String {
      let arch_halt = match cfg.arch {
          TargetArch::X86_64 => r#"loop { unsafe { core::arch::asm!("hlt"); } }"#,
          TargetArch::Arm64  => r#"loop { unsafe { core::arch::asm!("wfi"); } }"#,
          TargetArch::RiscV  => r#"loop { unsafe { core::arch::asm!("wfi"); } }"#,
          TargetArch::All    => r#"loop { unsafe { core::arch::asm!("hlt"); } }"#,
      };
      format!(r#"//! {name} bootloader entry point
  #![no_std]
  #![no_main]

  use {slug}_kernel::{{SubKernelManager, cap::{{CapabilityToken, CapRight}}}};
  use {slug}_kernel::subkernel::instance::SubKernelConfig;
  use {slug}_kernel::mm::ALLOCATOR;

  #[no_mangle]
  pub extern "C" fn _start() -> ! {{
      // Initialise the kernel
      let mut manager = SubKernelManager::new();

      // Spawn the init sub-kernel with full capabilities
      let root_cap = CapabilityToken::root();
      let _ = manager.spawn(
          SubKernelConfig {{ name: "init", mem_mb: 64 }},
          root_cap,
      );

      // Main kernel loop
      loop {{
          manager.tick_all();
          {halt}
      }}
  }}

  #[panic_handler]
  fn panic(_info: &core::panic::PanicInfo) -> ! {{
      {halt}
  }}
  "#, name = cfg.name, slug = cfg.slug, halt = arch_halt)
  }

  // ─── README.md ───────────────────────────────────────────────────────────────

  pub fn workspace_readme(cfg: &OsConfig) -> String {
      let features = if cfg.features.enabled_list().is_empty() {
          String::from("- Minimal kernel (cap system, scheduler, IPC, sub-kernel manager)")
      } else {
          cfg.features.enabled_list().iter()
              .map(|f| format!("- {}", f))
              .collect::<Vec<_>>()
              .join("\n")
      };

      format!(r#"# {name}

  > A sovereign OS generated by **Oxidiser** — the Re-Rust OS scaffolding tool.

  ## Architecture

  ```
  {name} Sovereign OS
  ├── kernel/{slug}       — master kernel (cap, mm, sched, ipc, sub-kernels)
  ├── core/{slug}-core    — shared types and traits
  ├── boot/{slug}-boot    — Ring -1 UEFI bootloader entry
  └── ...                 — optional feature modules
  ```

  ## Features enabled

  {features}

  ## Target architecture

  **{arch}**

  ## Build

  ```bash
  # Install the bare-metal target
  rustup target add {target}

  # Build the whole workspace
  cargo build --release

  # Build just the kernel
  cargo build -p {slug}-kernel --release
  ```

  ## Getting started

  Edit `kernel/{slug}/src/subkernel/manager.rs` to customise sub-kernel spawn logic.
  Edit `boot/{slug}-boot/src/main.rs` to add early hardware init.

  ---

  _Generated by [Oxidiser](https://github.com/Syedsmaeel/Proj.re-rust) — part of the Re-Rust / Timux ecosystem._
  "#,
          name    = cfg.name,
          slug    = cfg.slug,
          features= features,
          arch    = cfg.arch.display(),
          target  = cfg.arch.rust_target(),
      )
  }

