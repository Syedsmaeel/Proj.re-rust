//! File content templates for a generated sovereign OS workspace.
  //!
  //! Every template is a function that takes an `&OsConfig` and returns
  //! a `String` — the exact file content to write to disk.

  use crate::config::{OsConfig, TargetArch};

  // ─── Root Cargo.toml ─────────────────────────────────────────────────────────

  pub fn root_cargo(cfg: &OsConfig) -> String {
      let mut members = format!(
          "    "kernel/{name}",\n    "core/{name}-core",\n    "boot/{name}-boot",",
          name = cfg.slug
      );
      if cfg.features.networking { members.push_str(&format!("\n    "runtimes/{}-net",", cfg.slug)); }
      if cfg.features.ai         { members.push_str(&format!("\n    "runtimes/{}-llm",", cfg.slug)); }
      if cfg.features.blueprint  { members.push_str(&format!("\n    "utilities/{}-blueprint",", cfg.slug)); }

      format!(r#"[workspace]
  resolver = "2"
  members = [
  {members}
  ]

  [workspace.package]
  version      = "{ver}"
  edition      = "{ed}"
  authors      = ["{author}"]
  license      = "AGPL-3.0"
  repository   = ""

  [workspace.dependencies]
  anyhow    = "1"
  thiserror = "1"
  log       = "0.4"
  serde     = {{ version = "1", features = ["derive"] }}
  serde_json = "1"
  toml       = "0.8"
  clap       = {{ version = "4", features = ["derive"] }}
  "#,
          members = members,
          ver     = cfg.version,
          ed      = cfg.edition,
          author  = cfg.author,
      )
  }

