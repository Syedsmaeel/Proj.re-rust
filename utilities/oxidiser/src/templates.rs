  // ─── subkernel/instance.rs ───────────────────────────────────────────────────

  pub fn kernel_subkernel_instance(cfg: &OsConfig) -> String {
      format!(r#"//! SubKernel instance type for {name}
  extern crate alloc;
  use alloc::string::String;
  use crate::cap::CapabilityToken;

  pub type SubKernelId = u64;

  #[derive(Debug, Clone, Copy, PartialEq, Eq)]
  pub enum SubKernelState {{ Stopped, Running, Suspended, Crashed }}

  #[derive(Debug, Clone)]
  pub struct SubKernelConfig {{
      pub name:    &'static str,
      pub mem_mb:  u32,
  }}

  #[derive(Debug)]
  pub struct SubKernel {{
      pub id:     SubKernelId,
      pub config: SubKernelConfig,
      pub state:  SubKernelState,
      pub cap:    CapabilityToken,
      heartbeat:  u64,
  }}

  impl SubKernel {{
      pub fn new(id: SubKernelId, config: SubKernelConfig, cap: CapabilityToken) -> Self {{
          Self {{ id, config, state: SubKernelState::Stopped, cap, heartbeat: 0 }}
      }}
      pub fn start(&mut self)   {{ self.state = SubKernelState::Running; }}
      pub fn stop(&mut self)    {{ self.state = SubKernelState::Stopped; }}
      pub fn suspend(&mut self) {{ self.state = SubKernelState::Suspended; }}
      pub fn tick(&mut self)    {{ if self.state == SubKernelState::Running {{ self.heartbeat += 1; }} }}
      pub fn heartbeat(&self)   -> u64 {{ self.heartbeat }}
      pub fn is_running(&self)  -> bool {{ self.state == SubKernelState::Running }}
  }}
  "#, name = cfg.name)
  }

  // ─── subkernel/manager.rs ────────────────────────────────────────────────────

  pub fn kernel_subkernel_manager(cfg: &OsConfig) -> String {
      format!(r#"//! SubKernelManager for {name}
  extern crate alloc;
  use alloc::vec::Vec;
  use crate::cap::{{CapabilityToken, CapRight}};
  use super::instance::{{SubKernel, SubKernelId, SubKernelConfig, SubKernelState}};

  pub struct SubKernelManager {{
      sks:     Vec<SubKernel>,
      next_id: SubKernelId,
  }}

  impl SubKernelManager {{
      pub fn new() -> Self {{ Self {{ sks: Vec::new(), next_id: 1 }} }}

      pub fn spawn(&mut self, config: SubKernelConfig, cap: CapabilityToken) -> Result<SubKernelId, &'static str> {{
          if !cap.permits(CapRight::PROCESS_SPAWN) {{ return Err("no PROCESS_SPAWN right"); }}
          let id = self.next_id; self.next_id += 1;
          let mut sk = SubKernel::new(id, config, cap);
          sk.start();
          self.sks.push(sk);
          Ok(id)
      }}

      pub fn terminate(&mut self, id: SubKernelId) -> Result<(), &'static str> {{
          let sk = self.get_mut(id).ok_or("not found")?;
          sk.stop(); Ok(())
      }}

      pub fn suspend(&mut self, id: SubKernelId) -> Result<(), &'static str> {{
          let sk = self.get_mut(id).ok_or("not found")?;
          sk.suspend(); Ok(())
      }}

      pub fn tick_all(&mut self) {{ for sk in &mut self.sks {{ sk.tick(); }} }}

      pub fn get(&self, id: SubKernelId) -> Option<&SubKernel> {{
          self.sks.iter().find(|s| s.id == id)
      }}
      fn get_mut(&mut self, id: SubKernelId) -> Option<&mut SubKernel> {{
          self.sks.iter_mut().find(|s| s.id == id)
      }}
      pub fn count(&self) -> usize {{ self.sks.len() }}
      pub fn running(&self) -> usize {{ self.sks.iter().filter(|s| s.is_running()).count() }}
  }}
  "#, name = cfg.name)
  }

