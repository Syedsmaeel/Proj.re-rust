  // ─── cap.rs ──────────────────────────────────────────────────────────────────

  pub fn kernel_cap(cfg: &OsConfig) -> String {
      format!(r#"//! Capability system for {name}
  extern crate alloc;

  use alloc::string::String;

  bitflags::bitflags! {{
      #[derive(Debug, Clone, Copy, PartialEq, Eq)]
      pub struct CapRight: u64 {{
          const READ          = 1 << 0;
          const WRITE         = 1 << 1;
          const EXEC          = 1 << 2;
          const MAP           = 1 << 3;
          const SEND          = 1 << 4;
          const RECV          = 1 << 5;
          const PROCESS_SPAWN = 1 << 6;
          const FS_READ       = 1 << 7;
          const FS_WRITE      = 1 << 8;
          const NET_SEND      = 1 << 9;
          const NET_RECV      = 1 << 10;
          const CLOCK_READ    = 1 << 11;
          const ADMIN         = 1 << 63;
      }}
  }}

  #[derive(Debug, Clone)]
  pub struct CapabilityToken {{
      pub id:     u64,
      pub rights: CapRight,
      pub expiry: u64,
      valid:      bool,
  }}

  impl CapabilityToken {{
      pub fn new(id: u64, rights: CapRight) -> Self {{
          Self {{ id, rights, expiry: u64::MAX, valid: true }}
      }}
      pub fn root() -> Self {{ Self::new(0, CapRight::all()) }}
      pub fn is_valid(&self) -> bool {{ self.valid }}
      pub fn permits(&self, right: CapRight) -> bool {{ self.valid && self.rights.contains(right) }}
      pub fn revoke(&mut self) {{ self.valid = false; }}
  }}
  "#, name = cfg.name)
  }

