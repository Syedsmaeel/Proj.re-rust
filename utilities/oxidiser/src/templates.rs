  pub fn kernel_mm_allocator(_cfg: &OsConfig) -> String {
      r#"//! Simple bump allocator — replace with linked-list for production.
  use core::alloc::{GlobalAlloc, Layout};
  use core::cell::UnsafeCell;

  const HEAP_SIZE: usize = 4 * 1024 * 1024; // 4 MiB default

  pub struct BumpAllocator {
      heap:   UnsafeCell<[u8; HEAP_SIZE]>,
      offset: UnsafeCell<usize>,
  }

  unsafe impl Sync for BumpAllocator {}

  impl BumpAllocator {
      pub const fn new() -> Self {
          Self { heap: UnsafeCell::new([0u8; HEAP_SIZE]), offset: UnsafeCell::new(0) }
      }
  }

  unsafe impl GlobalAlloc for BumpAllocator {
      unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
          let off   = &mut *self.offset.get();
          let align = layout.align();
          let start = (*off + align - 1) & !(align - 1);
          let end   = start + layout.size();
          if end > HEAP_SIZE { return core::ptr::null_mut(); }
          *off = end;
          (self.heap.get() as *mut u8).add(start)
      }
      unsafe fn dealloc(&self, _ptr: *mut u8, _layout: Layout) {}
  }

  #[global_allocator]
  pub static ALLOCATOR: BumpAllocator = BumpAllocator::new();
  "#.into()
  }

  // ─── sched/mod.rs ─────────────────────────────────────────────────────────────

  pub fn kernel_sched(_cfg: &OsConfig) -> String {
      r#"//! Round-robin scheduler stub
  extern crate alloc;
  use alloc::collections::VecDeque;

  pub struct Scheduler {
      queue: VecDeque<u64>, // sub-kernel ids
  }
  impl Scheduler {
      pub fn new() -> Self { Self { queue: VecDeque::new() } }
      pub fn enqueue(&mut self, id: u64) { self.queue.push_back(id); }
      pub fn next(&mut self) -> Option<u64> {
          let id = self.queue.pop_front()?;
          self.queue.push_back(id);
          Some(id)
      }
      pub fn len(&self) -> usize { self.queue.len() }
  }
  "#.into()
  }

  // ─── ipc/mod.rs ───────────────────────────────────────────────────────────────

  pub fn kernel_ipc(_cfg: &OsConfig) -> String {
      r#"//! Basic IPC channel
  extern crate alloc;
  use alloc::collections::VecDeque;
  use alloc::vec::Vec;

  pub const MAX_MSG: usize = 4096;

  #[derive(Debug)]
  pub enum IpcError { ChannelFull, ChannelEmpty, PayloadTooLarge }

  pub struct Channel {
      pub id:    u64,
      buf:       VecDeque<Vec<u8>>,
      capacity:  usize,
  }
  impl Channel {
      pub fn new(id: u64) -> Self { Self { id, buf: VecDeque::new(), capacity: 64 } }
      pub fn send(&mut self, msg: Vec<u8>) -> Result<(), IpcError> {
          if msg.len() > MAX_MSG         { return Err(IpcError::PayloadTooLarge); }
          if self.buf.len() >= self.capacity { return Err(IpcError::ChannelFull); }
          self.buf.push_back(msg); Ok(())
      }
      pub fn recv(&mut self) -> Result<Vec<u8>, IpcError> {
          self.buf.pop_front().ok_or(IpcError::ChannelEmpty)
      }
      pub fn pending(&self) -> usize { self.buf.len() }
  }
  "#.into()
  }

